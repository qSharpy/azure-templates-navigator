/**
 * The plugin's tips: the `tipAndTrick` entries in plugin.xml, generated by Gradle from
 * shared/tips/tips.json. IntelliJ also mixes them into Help | Tip of the Day; this dialog shows
 * only ours, in order (the IDE's API for showing chosen tips is internal).
 */
object AtnTips {
    class Tip(val title: String, val html: String)

    private val TITLE = Regex("""<p><b>(.*?)</b></p>""")
    private val SHORTCUT = Regex("""&shortcut:([A-Za-z0-9_.]+);""")
    private val IMAGE = Regex("""<img src="images/([^"]+)\.png"""")

    fun all(): List<Tip> = TipAndTrickBean.EP_NAME.extensionList
        .filter { it.pluginDescriptor?.pluginId?.idString == PLUGIN_ID }
        .mapNotNull { bean ->
            val raw = AtnTips::class.java.classLoader.getResource("tips/${bean.fileName}")?.readText()
            if (raw == null) thisLogger().warn("[atn] tip file missing: tips/${bean.fileName}")
            raw?.let(::parse)
        }

    fun parse(raw: String): Tip {
        val body = raw.substringAfter("<body>").substringBefore("</body>")
        val title = TITLE.find(body)?.groupValues?.get(1) ?: ""
        // The IDE fills in &shortcut:Id; itself in Tip of the Day; this dialog has to do it.
        val withShortcuts = SHORTCUT.replace(body.replaceFirst(TITLE, "")) { m ->
            KeymapUtil.getFirstKeyboardShortcutText(m.groupValues[1]).ifEmpty {
                ActionManager.getInstance().getAction(m.groupValues[1])?.templateText ?: m.groupValues[1]
            }
        }
        // Tip of the Day resolves images/<name>.png to its @2x file; Swing's HTML needs the full URL. Its
        // width/height attributes are device pixels on a Retina screen, so the @2x file's own size draws it
        // at the size it was captured (and half that on a 1x screen, where it is twice too big otherwise).
        val html = IMAGE.replace(withShortcuts) { m ->
            val url = AtnTips::class.java.classLoader.getResource("tips/images/${m.groupValues[1]}@2x.png")
                ?: return@replace m.value
            val image = runCatching { javax.imageio.ImageIO.read(url) }.getOrNull() ?: return@replace m.value
            val scale = if (com.intellij.ui.scale.JBUIScale.sysScale() >= 2f) 1 else 2
            """<img width="${image.width / scale}" height="${image.height / scale}" src="$url""""
        }
        return Tip(title, html)
    }
}

class TipsDialog(project: Project?) : DialogWrapper(project, true) {
    private val tips = AtnTips.all()
    private var index = 0
    private val counter = JBLabel()
    private val heading = JBLabel().apply { font = JBUI.Fonts.label(16f).asBold() }
    private val pane = JEditorPane().apply {
        editorKit = HTMLEditorKitBuilder().withWordWrapViewFactory().build()
        isEditable = false
        isOpaque = false
        border = JBUI.Borders.empty()
        addHyperlinkListener { if (it.eventType == HyperlinkEvent.EventType.ACTIVATED) it.url?.let(BrowserUtil::browse) }
    }
    private val previous = object : AbstractAction("Previous") {
        override fun actionPerformed(e: ActionEvent) = show(index - 1)
    }
    private val next = object : AbstractAction("Next Tip") {
        override fun actionPerformed(e: ActionEvent) = show(index + 1)
    }
    private val docs = object : AbstractAction("Documentation") {
        override fun actionPerformed(e: ActionEvent) = BrowserUtil.browse(IssueReport.DOCS_URL)
    }

    init {
        title = "Azure Templates Navigator Tips"
        // Not modal: the point of a tip is to try it in the editor while it is open.
        isModal = false
        setCancelButtonText("Close")
        init()
        show(0)
    }

    private fun show(i: Int) {
        if (tips.isEmpty()) {
            heading.text = "No tips found"
            pane.text = "<p>See the documentation for what the plugin does.</p>"
            previous.isEnabled = false
            next.isEnabled = false
            return
        }
        index = i.coerceIn(0, tips.size - 1)
        counter.text = "Tip ${index + 1} of ${tips.size}"
        heading.text = tips[index].title
        pane.text = tips[index].html
        pane.caretPosition = 0
        previous.isEnabled = index > 0
        next.isEnabled = index < tips.size - 1
    }

    override fun createCenterPanel(): JComponent = JPanel(BorderLayout(0, JBUI.scale(8))).apply {
        add(JPanel(BorderLayout()).apply {
            isOpaque = false
            add(heading, BorderLayout.CENTER)
            add(counter.apply { foreground = JBUI.CurrentTheme.ContextHelp.FOREGROUND }, BorderLayout.EAST)
        }, BorderLayout.NORTH)
        add(JBScrollPane(pane).apply { border = JBUI.Borders.empty(); isOpaque = false; viewport.isOpaque = false }, BorderLayout.CENTER)
        preferredSize = JBUI.size(640, 560)
    }

    override fun createLeftSideActions(): Array<Action> = arrayOf(docs)
    override fun createActions(): Array<Action> = arrayOf(previous, next, cancelAction)
    override fun getPreferredFocusedComponent(): JComponent? = null
}

/** Help | Azure Templates Navigator Tips, Tools | Azure Templates, and "Get Started" in the tool window's help button. */
class ShowTipsAction : DumbAwareAction() {
    override fun getActionUpdateThread() = ActionUpdateThread.BGT
    override fun actionPerformed(e: AnActionEvent) = TipsDialog(e.project).show()
}

/**
 * Once per version, one balloon: after an update, What's New and Tips; when no version was
 * recorded yet (a new install, or an update from 2.6 or older), Tips. Stored per IDE, not per project.
 */
object AtnWelcome {
    private const val KEY = "azure-templates-navigator.lastVersion"

    fun announce(project: Project) {
        val version = PluginManagerCore.getPlugin(PluginId.getId(PLUGIN_ID))?.version ?: return
        val props = PropertiesComponent.getInstance()
        val seen = props.getValue(KEY)
        if (seen == version) return
        props.setValue(KEY, version)
        if (ApplicationManager.getApplication().isUnitTestMode) return
        val content = if (seen != null) "Updated to $version." else "Version $version. The tips show what it can do, one feature at a time."
        val notification = NotificationGroupManager.getInstance().getNotificationGroup("Azure Templates Navigator")
            .createNotification("Azure Templates Navigator", content, NotificationType.INFORMATION)
        if (seen != null) notification.addAction(NotificationAction.createSimpleExpiring("What's new") { BrowserUtil.browse(IssueReport.CHANGELOG_URL) })
        notification.addAction(NotificationAction.createSimpleExpiring("Show tips") { TipsDialog(project).show() })
        notification.notify(project)
    }
}
